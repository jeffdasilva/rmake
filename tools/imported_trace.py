"""Original exact directory-trace lifetime gate, with known workspace path inputs."""
import argparse
import base64
import json
import os
from pathlib import Path
import tempfile
import conformance as h
import oracle

ROOT=Path(__file__).resolve().parents[1]
MODELS=ROOT/'tests/research/imported-trace-models.json'


def inventory():
    return tuple(json.loads(MODELS.read_text())['cases'])


def expected(cell,work):
    result=dict(cell['expected_template'])
    output=bytes.fromhex(result['stdout_hex'])
    if cell['directory_placeholder']:
        if output.count(b'{WORK}')!=1:raise h.HarnessError('directory model needs exactly one workspace input')
        output=output.replace(b'{WORK}',os.fsencode(work))
    elif b'{WORK}'in output:
        raise h.HarnessError('unexpected workspace placeholder')
    result['stdout_hex']=output.hex()
    return result


def prepare(cell,path):
    path.mkdir(parents=True,exist_ok=True)
    for name,data in cell['inputs'].items():
        target=path/name
        target.parent.mkdir(parents=True,exist_ok=True)
        target.write_bytes(bytes.fromhex(data['hex']))
        target.chmod(data['mode'])
    h.validate_fixture(path)


def anchors(cell,observed,model):
    case=h.Case(Path('.'),cell['id'],'cli.imported-trace-ownership','required',(),5,{},model,'merged')
    errors=h.expectation_errors(case,observed)
    files={name:bytes.fromhex(data['hex'])for name,data in cell['inputs'].items()}
    if cell['expected_generated']:files['generated.mk']=b'# generated\n'
    directories={'work','home','tmp'}
    for name in files:
        directories.update('work/'+str(parent)for parent in Path(name).parents if str(parent)!='.')
    keys=directories|{'work/'+name for name in files}
    if set(observed.filesystem)!=keys:errors.append('exact source/generated filesystem membership')
    for name,data in files.items():
        actual=observed.filesystem.get('work/'+name,{})
        if actual.get('type')!='file'or actual.get('content')!=base64.b64encode(data).decode():errors.append('source/generated bytes: '+name)
        mode=cell['inputs'].get(name,{}).get('mode',0o644)
        if actual.get('mode')!=mode:errors.append('source/generated mode: '+name)
    for name in directories:
        if observed.filesystem.get(name,{}).get('type')!='directory':errors.append('directory topology: '+name)
    return errors


def run_cell(cell,fixture,workspace,binary):
    model=expected(cell,workspace/'work')
    case=h.Case(fixture,cell['id'],'cli.imported-trace-ownership','required',tuple(cell['args']),5,cell['environment'],model,'merged')
    observed=h.execute(case,workspace,binary)
    return observed,anchors(cell,observed,model)


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--oracle',type=Path,default=oracle.PREFIX/'bin/make')
    parser.add_argument('--candidate',type=Path)
    parser.add_argument('--self-test',action='store_true')
    parser.add_argument('--case',action='append',default=[])
    parser.add_argument('--artifacts',type=Path,default=ROOT/'artifacts/imported-trace')
    args=parser.parse_args(argv)
    if bool(args.candidate)==args.self_test:parser.error('choose candidate or self-test')
    reference=args.oracle.resolve();profile=oracle.verify(reference)
    candidate=reference if args.self_test else args.candidate.resolve()
    cells=inventory();ids={c['id']for c in cells}
    if len(ids)!=len(cells):raise h.HarnessError('duplicate imported-trace model')
    if set(args.case)-ids:parser.error('unknown case')
    if args.case:cells=tuple(c for c in cells if c['id']in args.case)
    args.artifacts.mkdir(parents=True,exist_ok=True)
    destination=Path(tempfile.mkdtemp(prefix='trace-ownership-',dir=args.artifacts.resolve()))
    workspace=destination/'workspace';workspace.mkdir();records=[];failures=0
    for cell in cells:
        fixture=destination/'fixtures'/cell['id'];prepare(cell,fixture)
        runs=[run_cell(cell,fixture,workspace,binary)for binary in (reference,reference,candidate)]
        observations=[o for o,_ in runs];errors=[e for _,e in runs]
        repeated=h.differences(*observations[:2]);difference=h.differences(observations[0],observations[2])
        bounds=[bool(o.limit or o.leftover_processes)for o in observations]
        failed=any(errors)or repeated or difference or any(bounds);failures+=bool(failed)
        print('FAIL'if failed else'PASS',cell['id'],errors,repeated,difference,flush=True)
        records.append(dict(id=cell['id'],args=cell['args'],environment=cell['environment'],inputs=cell['inputs'],expected_template=cell['expected_template'],expected=expected(cell,workspace/'work'),workspace_input=str(workspace/'work'),errors=errors,repeat=repeated,differences=difference,bounds=bounds,observations=[dict(h.observation_json(o),stdout_hex=o.stdout.hex(),stderr_hex=o.stderr.hex())for o in observations]))
    report=dict(classification='Original separately gated imported-trace profiles; zero additional ordinary or safety-exception credit.',profile=profile,identities={label:h.executable_identity(binary,oracle=label=='oracle')for label,binary in (('oracle',reference),('candidate',candidate))},records=records,failures=failures)
    path=destination/'report.json';path.write_text(json.dumps(report,indent=2)+'\n');print('Imported trace:',len(records),'profiles; failures=',failures,'Report:',path)
    return int(bool(failures))


if __name__=='__main__':
    try:raise SystemExit(main())
    except(h.HarnessError,oracle.OracleError,OSError,ValueError)as error:raise SystemExit(str(error))
